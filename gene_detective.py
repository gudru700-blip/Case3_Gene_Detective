def extract_gnomad_freq(values):
    """
    Приоритет:
    1. gnomadg — общая частота в геномной выборке;
    2. gnomade — общая частота в экзомной выборке.

    Популяционные частоты не подставляются вместо общей.
    """
    for source in ("gnomadg", "gnomade"):
        numbers = values.get(source, set())

        if not numbers:
            continue

        if len(numbers) != 1:
            return None, source, True

        return float(next(iter(numbers))), source, False

    return None, None, False


