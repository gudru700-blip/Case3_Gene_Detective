def fetch_variant_xml(variation_id):
    path = cache / f"variation_{variation_id}.xml"

    if path.exists():
        return ET.fromstring(path.read_bytes())

    for attempt in range(5):
        time.sleep(0.4)

        try:
            response = session.get(
                endpoint,
                params={
                    "db": "clinvar",
                    "rettype": "vcv",
                    "is_variationid": "1",
                    "id": variation_id,
                },
                timeout=(20, 120),
            )

            if response.status_code == 429 or response.status_code >= 500:
                response.raise_for_status()

            response.raise_for_status()
            root = ET.fromstring(response.content)
            for node in root.iter():
                node.tag = node.tag.split("}")[-1]

            if root.find(".//ERROR") is not None:
                raise ValueError(
                    root.findtext(".//ERROR")
                )

            if (
                root.tag != "VariationArchive"
                and root.find(".//VariationArchive") is None
            ):
                raise ValueError("ClinVar не вернул VariationArchive.")

            temporary = path.with_suffix(".tmp")
            temporary.write_bytes(ET.tostring(root, encoding="utf-8"))
            temporary.replace(path)
            return root

        except (
            requests.RequestException,
            ET.ParseError,
            ValueError,
        ):
            if attempt == 4:
                raise
            time.sleep(2 ** (attempt + 1))


def disease_id(db, identifier):
    db = db.strip()
    identifier = identifier.strip()

    if db.upper() == "OMIM":

        if re.fullmatch(r"\d{6}", identifier):
            return f"OMIM:{identifier}"
        return ""

    if db.upper() in {"ORPHANET", "ORPHA"}:
        number = identifier.split(":")[-1]
        return f"ORPHA:{number}" if number.isdigit() else ""

    if not db or not identifier:
        return ""

    return (
        identifier
        if identifier.startswith(db + ":")
        else f"{db}:{identifier}"
    )


def parse_variant(root, variant_id, variation_id):
    archives = (
        [root] if root.tag == "VariationArchive"
        else root.findall(".//VariationArchive")
    )

    archive = next(
        (
            item for item in archives
            if item.get("VariationID") == variation_id
        ),
        None,
    )

    if archive is None:
        raise ValueError("В ответе нет запрошенного VariationID.")

    exact_match = False

    for location in archive.findall(
        "./ClassifiedRecord/SimpleAllele/.//SequenceLocation"
    ):
        if location.get("Assembly") != "GRCh38":
            continue

        chrom = "chr" + location.get("Chr", "").removeprefix("chr")
        key = ":".join([
            chrom,
            location.get("positionVCF", ""),
            location.get("referenceAlleleVCF", ""),
            location.get("alternateAlleleVCF", ""),
        ])

        if key == variant_id:
            exact_match = True

    if not exact_match:
        raise ValueError(
            f"Аллель {variant_id} не подтверждён в XML GRCh38."
        )

    trait_maps = defaultdict(lambda: defaultdict(set))

    for trait_set in archive.findall(".//TraitSet"):
        set_id = trait_set.get("ID")

        if not set_id:
            continue

        for trait in trait_set.findall("./Trait"):
            ids = {
                disease_id(x.get("DB", ""), x.get("ID", ""))
                for x in trait.findall(".//XRef")
            }
            ids.discard("")

            for identifier in ids:
                trait_maps[set_id][identifier].update(ids)

    records = []

    for rcv in archive.findall(
        "./ClassifiedRecord/RCVList/RCVAccession"
    ):
        condition_list = rcv.find("./ClassifiedConditionList")
        if condition_list is None:
            continue

        set_id = condition_list.get("TraitSetID", "")
        conditions = []

        for condition in condition_list.findall("./ClassifiedCondition"):
            identifier = disease_id(
                condition.get("DB", ""),
                condition.get("ID", ""),
            )

            ids = {identifier} if identifier else set()
            ids.update(trait_maps[set_id].get(identifier, set()))

            conditions.append({
                "name": (condition.text or "").strip(),
                "ids": sorted(ids),
            })

        germline = rcv.find(
            "./RCVClassifications/GermlineClassification"
        )

        records.append({
            "rcv": rcv.get("Accession", ""),
            "version": rcv.get("Version", ""),
            "conditions": conditions,
            "multiple_conditions": len(conditions) > 1,
            "classification": (
                germline.findtext("./Description", default="")
                if germline is not None else ""
            ),
            "review_status": (
                germline.findtext("./ReviewStatus", default="")
                if germline is not None else ""
            ),
        })

    return records


